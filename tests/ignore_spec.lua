    H.ok(not tracked(dir, "a.cfg"))
    H.eq(H.read(dir, ".gitignore"), "*.cfg\n")
    H.eq(H.find_entry(view, "untracked", "b.cfg"), nil)
  end)

  H.it("a tracked name with wildcards untracks only itself", function()
    local dir = repo({ ["a*"] = { "star" }, ["ab"] = { "b" }, ["d[x]/f"] = { "f" }, ["dx/f"] = { "g" } })
    H.write(dir, "a*", { "STAR" })
    H.write(dir, "d[x]/f", { "F" })
    local view = open()
    answer(".gitignore: /a\\*")
    press(view, "unstaged", "a*")
    H.ok(not tracked(dir, "a*"))
    H.ok(tracked(dir, "ab"))
    answer(".gitignore: /d\\[x]/")
    press(view, "unstaged", "d[x]")
    H.ok(not tracked(dir, "d[x]/f"))
    H.ok(tracked(dir, "dx/f"))
    H.ok(ignored(dir, "d[x]/f") and not ignored(dir, "dx/f"))
  end)
end)

H.describe("i: what the review found", function()
  H.it("during a merge, what the other side committed counts as committed", function()
    local dir = repo({ ["c.txt"] = { "base" } })
    H.git(dir, { "checkout", "-q", "-b", "other" })
    H.commit(dir, "other", { ["c.txt"] = { "theirs" }, ["tool.cfg"] = { "t" } })
    H.git(dir, { "checkout", "-q", "main" })
    H.commit(dir, "mine", { ["c.txt"] = { "mine" } })
    vim.system({ "git", "merge", "-q", "other" }, { cwd = dir }):wait()
    local view = open()
    confirm_answer = 2
    answer(".gitignore: /tool.cfg")
    press(view, "staged", "tool.cfg")
    H.eq(#asked, 1, "asked")
    H.ok(asked[1]:find("deletes it from the repository", 1, true), asked[1])
    H.ok(tracked(dir, "tool.cfg"))
  end)

  H.it("a rename into a directory: asked, by its old name too", function()
    local dir = repo({ ["a.txt"] = { "a" }, ["d/other.txt"] = { "o" } })
    H.git(dir, { "mv", "a.txt", "d/a.txt" })
    H.write(dir, "d/new.txt", { "n" })
    H.write(dir, "d/other.txt", { "O" })
    local view = open()
    confirm_answer = 2
    answer(".gitignore: /d/")
    press(view, "untracked", "d")
    H.eq(#asked, 1)
    H.ok(asked[1]:find("d/a.txt (was a.txt)", 1, true), asked[1])
    H.ok(not asked[1]:find("never committed", 1, true), asked[1])
  end)

  H.it("copies are not renames (diff.renames = copies)", function()
    local dir = repo({ ["a.txt"] = H.lines(20) })
    H.git(dir, { "config", "diff.renames", "copies" })
    H.git(dir, { "config", "status.renames", "copies" })
    H.write(dir, "b.txt", H.lines(20))
    H.git(dir, { "add", "b.txt" })
    local view = open()
    answer(".gitignore: /b.txt")
    press(view, "staged", "b.txt")
    H.eq(#asked, 0, "b.txt was never committed")
    H.ok(not tracked(dir, "b.txt"))
    H.ok(tracked(dir, "a.txt"))
  end)

  H.it("a directory with more tracked files than a command line holds", function()
    local dir = repo({ ["keep.txt"] = { "k" } })
    local long = string.rep("x", 180)
    vim.fn.mkdir(dir .. "/nm", "p")
    for i = 1, 12000 do
      local f = assert(io.open(("%s/nm/%s%05d"):format(dir, long, i), "wb"))
      f:write("a")
      f:close()
    end
    H.git(dir, { "add", "-A" })
    H.git(dir, { "commit", "-q", "-m", "oops" })
    H.write(dir, "nm/new", { "n" })
    local view = open()
    answer(".gitignore: /nm/")
    local msg = messages(function()
      press(view, "untracked", "nm")
    end)
    H.ok(asked[1] and asked[1]:find("12000 files are tracked", 1, true), asked[1] or msg)
    H.eq(vim.trim(H.git(dir, { "ls-files" })), "keep.txt")
    H.ok(msg:find("12000 files no longer tracked", 1, true), msg)
  end)

  H.it("a conflict under a directory: refused, nothing changed", function()
    local dir = repo({ ["d/c.txt"] = { "base" } })
    H.git(dir, { "checkout", "-q", "-b", "other" })
    H.commit(dir, "other", { ["d/c.txt"] = { "theirs" } })
    H.git(dir, { "checkout", "-q", "main" })
    H.commit(dir, "mine", { ["d/c.txt"] = { "mine" } })
    vim.system({ "git", "merge", "-q", "other" }, { cwd = dir }):wait()
    H.write(dir, "d/new.txt", { "n" })
    local view = open()
    answer(".gitignore: /d/")
    local msg = messages(function()
      press(view, "untracked", "d")
    end)
    H.ok(msg:find("resolve the conflict first: d/c.txt", 1, true), msg)
    H.eq(#asked, 0)
    H.eq(H.read(dir, ".gitignore"), nil)
    H.ok(vim.trim(H.git(dir, { "ls-files", "-u" })) ~= "", "still in conflict")
  end)

  H.it("the ignore file cannot be written: the index is left as it is", function()
    local dir = repo({ ["cfg.lua"] = { "a" }, [".gitignore"] = { "*.o" } })
    H.write(dir, "cfg.lua", { "b" })
    vim.uv.fs_chmod(dir .. "/.gitignore", tonumber("444", 8))
    local view = open()
    answer(".gitignore: /cfg.lua")
    local msg = messages(function()
      press(view, "unstaged", "cfg.lua")
    end)
    vim.uv.fs_chmod(dir .. "/.gitignore", tonumber("644", 8))
    H.ok(msg:find("cannot write .gitignore", 1, true), msg)
    H.ok(tracked(dir, "cfg.lua"))
    H.eq(H.read(dir, ".gitignore"), "*.o\n")
  end)

  H.it("git rm --cached failing puts the ignore file back", function()
    local dir = repo({ ["a.txt"] = { "a" }, [".gitignore"] = "*.o" })
    H.write(dir, "a.txt", { "b" })
    H.write(dir, "x.txt", { "x" })
    local view = open()
    H.write(dir, ".git/index.lock", "")
    answer(".gitignore: /a.txt")
    local msg = messages(function()
      press(view, "unstaged", "a.txt")
    end)
    H.ok(msg:find("git rm --cached failed (nothing changed)", 1, true), msg)
    H.eq(H.read(dir, ".gitignore"), "*.o")
    -- a file that was not there goes again
    os.remove(dir .. "/.git/index.lock")
    H.git(dir, { "rm", "-q", "--cached", ".gitignore" })
    os.remove(dir .. "/.gitignore")
    H.write(dir, ".git/index.lock", "")
    answer(".gitignore: /a.txt")
    press(view, "unstaged", "a.txt")
    H.eq(H.read(dir, ".gitignore"), nil)
    os.remove(dir .. "/.git/index.lock")
    H.ok(tracked(dir, "a.txt"))
  end)
end)

