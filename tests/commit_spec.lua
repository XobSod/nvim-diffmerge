-- Committing from the status view: `git commit` itself, its message edited in this Neovim.
local H = dofile(vim.fn.fnamemodify(debug.getinfo(1, "S").source:sub(2), ":p:h") .. "/harness.lua")
local api = vim.api
local commit = require("diffmerge.commit")

local function repo(files)
  local dir = H.repo(files)
  H.git(dir, { "branch", "-m", "master" })
  vim.cmd.cd(dir)
  return dir
end

local function open()
  local view = require("diffmerge").status()
  api.nvim_set_current_win(view.layout.files_win)
  return view
end

local function press(view, action)
  api.nvim_set_current_win(view.layout.files_win)
  view:dispatch(action, { buf = view.files.buf, win = view.layout.files_win })
end

--- The window git's editor opened (nil after `ms`).
local function message_win(ms)
  local win
  vim.wait(ms or 5000, function()
    for _, w in ipairs(api.nvim_list_wins()) do
      if api.nvim_buf_get_name(api.nvim_win_get_buf(w)):match("COMMIT_EDITMSG$") then
        win = w
        return true
      end
    end
    return false
  end, 20)
  return win
end

local function finished()
  return vim.wait(10000, function()
    return not commit.running()
  end, 20)
end

local function messages(fn)
  local got, notify = {}, vim.notify
  vim.notify = function(msg)
    got[#got + 1] = msg
  end
  local ok, err = pcall(fn)
  vim.notify = notify
  assert(ok, err)
  return table.concat(got, "\n")
end

local function subject(dir, rev)
  return vim.trim(H.git(dir, { "log", "-1", "--format=%s", rev or "HEAD" }))
end

--- Closes the message window with `cmd` typed on the command line (as you would: :q! aborts
--- by what was typed).
local function close_message(win, cmd)
  api.nvim_set_current_win(win)
  api.nvim_feedkeys(api.nvim_replace_termcodes(":" .. cmd .. "<CR>", true, false, true), "xt", false)
end

local function hook(dir, name, body)
  local path = dir .. "/.git/hooks/" .. name
  H.write(dir, ".git/hooks/" .. name, { "#!/bin/sh", body })
  vim.uv.fs_chmod(path, 493)
end

H.describe("committing", function()
  H.it("cc: git's message template in a window below, :wq commits", function()
    local dir = repo({ ["a.txt"] = { "a" } })
    H.write(dir, "a.txt", { "A" })
    H.git(dir, { "add", "a.txt" })
    local view = open()
    press(view, "commit")
    local win = message_win()
    H.ok(win, "the message window")
    H.eq(api.nvim_win_get_tabpage(win), view.layout.tab)
    local buf = api.nvim_win_get_buf(win)
    local text = table.concat(H.buf_lines(buf), "\n")
    H.ok(text:find("# Changes to be committed:", 1, true), text)
    H.ok(text:find("modified:   a.txt", 1, true), text)
    H.eq(vim.bo[buf].filetype, "gitcommit")
    api.nvim_buf_set_lines(buf, 0, 1, false, { "Change a" })
    local said = messages(function()
      close_message(win, "silent wq")
      H.ok(finished(), "git finished")
    end)
    H.eq(subject(dir), "Change a")
    H.ok(said:find("[master ", 1, true), said)
    H.eq(H.find_entry(view, "staged", "a.txt"), nil, "the view follows")
  end)

  H.it("an empty message aborts, as git does", function()
    local dir = repo({ ["a.txt"] = { "a" } })
    H.write(dir, "a.txt", { "A" })
    H.git(dir, { "add", "a.txt" })
    local view = open()
    press(view, "commit")
    local win = message_win()
    local said = messages(function()
      close_message(win, "q!")
      H.ok(finished(), "git finished")
    end)
    H.eq(subject(dir), "initial")
    H.ok(said:find("commit aborted", 1, true), said)
  end)

  H.it("ca: amend, with the last message to edit", function()
    local dir = repo({ ["a.txt"] = { "a" } })
    H.commit(dir, "first try", { ["a.txt"] = { "A" } })
    H.write(dir, "b.txt", { "b" })
    H.git(dir, { "add", "b.txt" })
    local count = vim.trim(H.git(dir, { "rev-list", "--count", "HEAD" }))
    local view = open()
    press(view, "commit_amend")
    local win = message_win()
    local buf = api.nvim_win_get_buf(win)
    H.eq(H.buf_lines(buf)[1], "first try")
    api.nvim_buf_set_lines(buf, 0, 1, false, { "Add a and b" })
    close_message(win, "silent wq")
    H.ok(finished(), "git finished")
    H.eq(subject(dir), "Add a and b")
    H.eq(vim.trim(H.git(dir, { "rev-list", "--count", "HEAD" })), count)
    H.eq(H.git(dir, { "show", "--name-only", "--format=", "HEAD" }), "a.txt\nb.txt\n")
  end)

  H.it("git's hooks run: a failing pre-commit stops it, commit-msg can rewrite", function()
    local dir = repo({ ["a.txt"] = { "a" } })
    H.write(dir, "a.txt", { "A" })
    H.git(dir, { "add", "a.txt" })
    hook(dir, "pre-commit", 'echo "lint: a.txt is not formatted"; exit 1')
    local view = open()
    local said = messages(function()
      press(view, "commit")
      H.ok(finished(), "git finished")
    end)
    H.ok(said:find("lint: a.txt is not formatted", 1, true), said)
    H.eq(message_win(200), nil, "no message window")
    H.eq(subject(dir), "initial")
    os.remove(dir .. "/.git/hooks/pre-commit")
    hook(dir, "commit-msg", 'sed -i "1s/^/[x] /" "$1"')
    press(view, "commit")
    local win = message_win()
    api.nvim_buf_set_lines(api.nvim_win_get_buf(win), 0, 1, false, { "Change a" })
    close_message(win, "silent wq")
    H.ok(finished(), "git finished")
    H.eq(subject(dir), "[x] Change a")
  end)

  H.it("finishing a merge: git's merge message, two parents", function()
    local dir = repo({ ["f.txt"] = { "a" } })
    H.git(dir, { "checkout", "-q", "-b", "feat" })
    H.commit(dir, "feat", { ["f.txt"] = { "F" } })
    H.git(dir, { "checkout", "-q", "master" })
    H.commit(dir, "master", { ["f.txt"] = { "M" } })
    vim.system({ "git", "merge", "-q", "feat" }, { cwd = dir }):wait()
    H.write(dir, "f.txt", { "M and F" })
    H.git(dir, { "add", "f.txt" })
    local view = open()
    press(view, "commit")
    local win = message_win()
    H.eq(H.buf_lines(api.nvim_win_get_buf(win))[1], "Merge branch 'feat'")
    close_message(win, "silent wq")
    H.ok(finished(), "git finished")
    H.eq(subject(dir), "Merge branch 'feat'")
    H.eq(#vim.split(vim.trim(H.git(dir, { "log", "-1", "--format=%P" })), " "), 2)
  end)

  H.it("nothing staged: git says so", function()
    local dir = repo({ ["a.txt"] = { "a" } })
    H.write(dir, "a.txt", { "A" })
    local view = open()
    local said = messages(function()
      press(view, "commit")
      H.ok(finished(), "git finished")
    end)
    H.ok(said:find("no changes added to commit", 1, true), said)
    H.eq(message_win(200), nil)
  end)

  H.it(":DiffMerge commit passes its arguments; one commit at a time", function()
    local dir = repo({ ["a.txt"] = { "a" } })
    vim.cmd("DiffMerge commit --allow-empty -m Empty")
    H.ok(finished(), "git finished")
    H.eq(subject(dir), "Empty")
    H.write(dir, "a.txt", { "A" })
    H.git(dir, { "add", "a.txt" })
    local view = open()
    press(view, "commit")
    local win = message_win()
    local said = messages(function()
      press(view, "commit")
    end)
    H.ok(said:find("a commit is waiting for its message", 1, true), said)
    close_message(win, "q!")
    H.ok(finished(), "git finished")
  end)
  H.it(":q! aborts a message git filled in (amend, merge)", function()
    local dir = repo({ ["a.txt"] = { "a" } })
    H.commit(dir, "first", { ["a.txt"] = { "A" } })
    H.write(dir, "b.txt", { "b" })
    H.git(dir, { "add", "b.txt" })
    local head = vim.trim(H.git(dir, { "rev-parse", "HEAD" }))
    local view = open()
    press(view, "commit_amend")
    local said = messages(function()
      close_message(message_win(), "q!")
      H.ok(finished(), "git finished")
    end)
    H.ok(said:find("commit aborted", 1, true), said)
    H.eq(vim.trim(H.git(dir, { "rev-parse", "HEAD" })), head, "not amended")
    -- a merge: still in progress
    H.git(dir, { "commit", "-q", "-m", "b" })
    H.git(dir, { "checkout", "-q", "-b", "feat" })
    H.commit(dir, "feat", { ["a.txt"] = { "F" } })
    H.git(dir, { "checkout", "-q", "master" })
    H.commit(dir, "master side", { ["a.txt"] = { "M" } })
    vim.system({ "git", "merge", "-q", "feat" }, { cwd = dir }):wait()
    H.write(dir, "a.txt", { "M F" })
    H.git(dir, { "add", "a.txt" })
    view:refresh()
    press(view, "commit")
    close_message(message_win(), "q!")
    H.ok(finished(), "git finished")
    H.ok(vim.uv.fs_stat(dir .. "/.git/MERGE_HEAD"), "the merge goes on")
  end)

  H.it("the view does not close while a message is open; staging waits", function()
    local dir = repo({ ["a.txt"] = { "a" }, ["b.txt"] = { "b" } })
    H.write(dir, "a.txt", { "A" })
    H.write(dir, "b.txt", { "B" })
    H.git(dir, { "add", "a.txt" })
    local view = open()
    press(view, "commit")
    local win = message_win()
    local said = messages(function()
      view:dispatch("close", { buf = view.files.buf, win = view.layout.files_win })
      press(view, "stage_all")
    end)
    H.ok(said:find("a commit message is open in this tab", 1, true), said)
    H.ok(said:find("a commit is running", 1, true), said)
    H.ok(api.nvim_win_is_valid(win), "the message window stays")
    H.eq(H.git(dir, { "diff", "--cached", "--name-only" }), "a.txt\n", "b.txt not staged")
    close_message(win, "q!")
    H.ok(finished(), "git finished")
  end)

  H.it("a swap file or an old buffer of the message file is no obstacle", function()
    local dir = repo({ ["a.txt"] = { "a" } })
    H.write(dir, "a.txt", { "A" })
    H.git(dir, { "add", "a.txt" })
    -- a swap file left behind by a Neovim that died editing the message
    local swapdir = H.tmpdir()
    local msg = dir .. "/.git/COMMIT_EDITMSG"
    H.write(dir, ".git/COMMIT_EDITMSG", { "an old message" })
    local dead = vim.system({ "nvim", "--headless", "--clean", "--cmd", "set swapfile directory=" .. swapdir .. "//", msg, "-c", "normal! iunsaved", "-c", "preserve" })
    vim.wait(5000, function()
      return #vim.fn.glob(swapdir .. "/*", false, true) > 0
    end)
    dead:kill(9)
    dead:wait()
    -- (swap files are only looked at by a Neovim started normally, not by -l)
    local script = H.tmpdir() .. "/commit.lua"
    H.write(vim.fs.dirname(script), "commit.lua", {
      "local view = require('diffmerge').status()",
      "vim.api.nvim_set_current_win(view.layout.files_win)",
      "view:dispatch('commit', { buf = view.files.buf, win = view.layout.files_win })",
      "local win",
      "vim.wait(5000, function() for _, w in ipairs(vim.api.nvim_list_wins()) do if vim.api.nvim_buf_get_name(vim.api.nvim_win_get_buf(w)):match('COMMIT_EDITMSG$') then win = w return true end end end, 20)",
      "vim.api.nvim_buf_set_lines(vim.api.nvim_win_get_buf(win), 0, 1, false, { 'Through' })",
      "vim.api.nvim_win_call(win, function() vim.cmd('silent wq') end)",
      "vim.wait(10000, function() return not require('diffmerge.commit').running() end, 20)",
      "vim.cmd('qa!')",
    })
    local res = vim.system({
      "nvim", "--headless", "--clean",
      "--cmd", "set rtp^=" .. H.root .. " swapfile directory=" .. swapdir .. "//",
      "-c", "luafile " .. script,
    }, { cwd = dir, text = true }):wait(30000)
    H.ok(not (res.stderr or ""):find("E325", 1, true), res.stderr)
    H.eq(subject(dir), "Through")
    -- a buffer of the message file from before (here: not shown anywhere)
    H.write(dir, "a.txt", { "AA" })
    H.git(dir, { "add", "a.txt" })
    vim.fn.bufload(vim.fn.bufadd(msg))
    local view = open()
    press(view, "commit")
    local win = message_win()
    api.nvim_buf_set_lines(api.nvim_win_get_buf(win), 0, 1, false, { "Again" })
    close_message(win, "silent wq")
    H.ok(finished(), "git finished")
    H.eq(subject(dir), "Again")
  end)

  H.it("quoted arguments; the summary in one line; a message offered again", function()
    local dir = repo({ ["a.txt"] = { "a" } })
    vim.cmd([[DiffMerge commit --allow-empty -m "two words"]])
    H.ok(finished(), "git finished")
    H.eq(subject(dir), "two words")
    H.write(dir, "a.txt", { "A" })
    H.git(dir, { "add", "a.txt" })
    local said = messages(function()
      vim.cmd([[DiffMerge commit -q -m quiet]])
      H.ok(finished(), "git finished")
    end)
    H.ok(said:match("committed %x+ quiet"), said)
    -- rejected by commit-msg after it was written: the next commit starts with it
    H.write(dir, "a.txt", { "AA" })
    H.git(dir, { "add", "a.txt" })
    hook(dir, "commit-msg", 'echo "no ticket number"; exit 1')
    local view = open()
    press(view, "commit")
    local win = message_win()
    api.nvim_buf_set_lines(api.nvim_win_get_buf(win), 0, 1, false, { "Work on a" })
    said = messages(function()
      close_message(win, "silent wq")
      H.ok(finished(), "git finished")
    end)
    H.ok(said:find("no ticket number", 1, true), said)
    os.remove(dir .. "/.git/hooks/commit-msg")
    press(view, "commit")
    win = message_win()
    H.eq(H.buf_lines(api.nvim_win_get_buf(win))[1], "Work on a")
    close_message(win, "silent wq")
    H.ok(finished(), "git finished")
    H.eq(subject(dir), "Work on a")
  end)

  H.it("a slow hook: you can work elsewhere, the message waits for you there", function()
    local dir = repo({ ["a.txt"] = { "a" } })
    H.write(dir, "a.txt", { "A" })
    H.git(dir, { "add", "a.txt" })
    hook(dir, "pre-commit", "sleep 1")
    local view = open()
    press(view, "commit")
    vim.cmd("tabnew")
    local elsewhere = api.nvim_get_current_tabpage()
    local win = message_win()
    H.eq(api.nvim_get_current_tabpage(), elsewhere, "not pulled back")
    H.eq(api.nvim_win_get_tabpage(win), view.layout.tab)
    close_message(win, "q!")
    H.ok(finished(), "git finished")
  end)

  H.it("c: a menu (commit / amend)", function()
    local dir = repo({ ["a.txt"] = { "a" } })
    H.commit(dir, "first", { ["a.txt"] = { "A" } })
    local view = open()
    vim.ui.select = function(items, opts, cb)
      for _, it in ipairs(items) do
        if opts.format_item(it):match("^Amend") then
          return cb(it)
        end
      end
    end
    press(view, "commit_menu")
    local win = message_win()
    H.eq(H.buf_lines(api.nvim_win_get_buf(win))[1], "first")
    close_message(win, "q!")
    H.ok(finished(), "git finished")
  end)
  H.it("ZZ takes git's message as it is; ZQ aborts", function()
    local dir = repo({ ["a.txt"] = { "a" } })
    H.commit(dir, "first", { ["a.txt"] = { "A" } })
    H.write(dir, "b.txt", { "b" })
    H.git(dir, { "add", "b.txt" })
    local view = open()
    press(view, "commit_amend")
    api.nvim_set_current_win(message_win())
    api.nvim_feedkeys("ZZ", "xt", false)
    H.ok(finished(), "git finished")
    H.eq(H.git(dir, { "show", "--name-only", "--format=%s", "HEAD" }), "first\n\na.txt\nb.txt\n", "amended")
    H.write(dir, "c.txt", { "c" })
    H.git(dir, { "add", "c.txt" })
    view:refresh()
    local head = vim.trim(H.git(dir, { "rev-parse", "HEAD" }))
    press(view, "commit_amend")
    api.nvim_set_current_win(message_win())
    api.nvim_feedkeys("ZQ", "xt", false)
    H.ok(finished(), "git finished")
    H.eq(vim.trim(H.git(dir, { "rev-parse", "HEAD" })), head, "not amended")
  end)

  H.it("c waits for cc / ca, the two-key mappings do not wait", function()
    repo({ ["a.txt"] = { "a" } })
    local view = open()
    local function nowait(lhs)
      return vim.api.nvim_buf_call(view.files.buf, function()
        return vim.fn.maparg(lhs, "n", false, true).nowait
      end)
    end
    H.eq({ nowait("c"), nowait("cc"), nowait("ca"), nowait("s") }, { 0, 1, 1, 1 })
  end)

  H.it("a float in the status tab; the message across the bottom of it", function()
    local dir = repo({ ["a.txt"] = { "a" } })
    H.write(dir, "a.txt", { "A" })
    H.git(dir, { "add", "a.txt" })
    hook(dir, "pre-commit", "sleep 1")
    local view = open()
    press(view, "commit")
    api.nvim_open_win(api.nvim_create_buf(false, true), false, {
      relative = "editor", row = 1, col = 1, width = 20, height = 2, focusable = false,
    })
    vim.cmd("tabnew")
    local win = message_win()
    H.ok(win, "opened")
    H.eq(api.nvim_win_get_tabpage(win), view.layout.tab)
    H.eq(api.nvim_win_get_width(win), vim.o.columns)
    close_message(win, "q!")
    H.ok(finished(), "git finished")
  end)

  H.it("stopping a hook that does not end", function()
    local dir = repo({ ["a.txt"] = { "a" } })
    H.write(dir, "a.txt", { "A" })
    H.git(dir, { "add", "a.txt" })
    hook(dir, "pre-commit", "sleep 30")
    local view = open()
    press(view, "commit")
    vim.wait(300)
    local t = vim.uv.hrtime()
    local confirm = vim.fn.confirm
    vim.fn.confirm = function()
      return 1
    end
    local said = messages(function()
      press(view, "commit")
      H.ok(finished(), "git finished")
    end)
    vim.fn.confirm = confirm
    H.ok((vim.uv.hrtime() - t) / 1e9 < 5, "stopped at once")
    H.ok(said:find("git commit stopped", 1, true), said)
    H.eq(subject(dir), "initial")
  end)

  H.it("a hook's whole output; --dry-run commits nothing", function()
    local dir = repo({ ["a.txt"] = { "a" } })
    H.write(dir, "a.txt", { "A" })
    H.git(dir, { "add", "a.txt" })
    hook(dir, "pre-commit", 'printf "lint failed:\\n\\tsrc/a.lua:3: unused variable x\\nChanges needed in 2 files\\n"; exit 1')
    local view = open()
    local said = messages(function()
      press(view, "commit")
      H.ok(finished(), "git finished")
    end)
    H.ok(said:find("\tsrc/a.lua:3: unused variable x", 1, true), said)
    H.ok(said:find("Changes needed in 2 files", 1, true), said)
    os.remove(dir .. "/.git/hooks/pre-commit")
    said = messages(function()
      vim.cmd("DiffMerge commit --dry-run")
      H.ok(finished(), "git finished")
    end)
    H.ok(said:find("nothing was committed", 1, true), said)
  end)

  H.it("the message window moved to its own tab (<C-w>T) still commits", function()
    local dir = repo({ ["a.txt"] = { "a" } })
    H.write(dir, "a.txt", { "A" })
    H.git(dir, { "add", "a.txt" })
    local view = open()
    press(view, "commit")
    api.nvim_set_current_win(message_win())
    vim.cmd("wincmd T")
    local win = api.nvim_get_current_win()
    api.nvim_buf_set_lines(api.nvim_win_get_buf(win), 0, 1, false, { "Moved" })
    close_message(win, "silent wq")
    H.ok(finished(), "git finished")
    H.eq(subject(dir), "Moved")
  end)

  H.it("a message offered again stays in its repository", function()
    local a = repo({ ["a.txt"] = { "a" } })
    H.write(a, "a.txt", { "A" })
    H.git(a, { "add", "a.txt" })
    hook(a, "commit-msg", "exit 1")
    local view = open()
    press(view, "commit")
    local win = message_win()
    api.nvim_buf_set_lines(api.nvim_win_get_buf(win), 0, 1, false, { "Message of a" })
    close_message(win, "silent wq")
    H.ok(finished(), "git finished")
    view:close()
    local b = repo({ ["b.txt"] = { "b" } })
    H.write(b, "b.txt", { "B" })
    H.git(b, { "add", "b.txt" })
    local view_b = open()
    press(view_b, "commit")
    win = message_win()
    H.ok(H.buf_lines(api.nvim_win_get_buf(win))[1] ~= "Message of a", "not offered here")
    close_message(win, "q!")
    H.ok(finished(), "git finished")
  end)
end)

H.done()
