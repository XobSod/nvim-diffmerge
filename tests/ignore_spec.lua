-- Ignoring files from the file panel (i): .gitignore / .git/info/exclude, by path or extension.
local H = dofile(vim.fn.fnamemodify(debug.getinfo(1, "S").source:sub(2), ":p:h") .. "/harness.lua")
local api = vim.api

local confirm_answer, asked = 1, {}
vim.fn.confirm = function(question)
  asked[#asked + 1] = question
  return confirm_answer
end

local menu
--- Answers the next menu with the choice shown as `text` (and keeps the menu in `menu`).
local function answer(text)
  vim.ui.select = function(items, opts, cb)
    menu = vim.tbl_map(opts.format_item, items)
    for _, it in ipairs(items) do
      if opts.format_item(it) == text then
        return cb(it)
      end
    end
    error("no choice " .. text .. " in " .. vim.inspect(menu))
  end
end

local function repo(files)
  local dir = H.repo(files)
  vim.cmd.cd(dir)
  confirm_answer, asked, menu = 1, {}, nil
  return dir
end

local function open()
  local view = require("diffmerge").status()
  api.nvim_set_current_win(view.layout.files_win)
  return view
end

local function line_of(view, section, path)
  for l = 1, api.nvim_buf_line_count(view.files.buf) do
    local it = view.files:item_at(l)
    if it and it.section and it.section.id == section then
      if (it.kind == "file" and it.entry.path == path) or (it.kind == "dir" and it.node.path == path) then
        return l
      end
    end
  end
  error(("no line for %s:%s"):format(section, path))
end

--- `i` on the line(s) of `section`'s `path` (a list: visual over them).
local function press(view, section, path)
  api.nvim_set_current_win(view.layout.files_win)
  local range
  if type(path) == "table" then
    local a, b = line_of(view, section, path[1]), line_of(view, section, path[#path])
    range = { math.min(a, b), math.max(a, b) }
    api.nvim_win_set_cursor(0, { range[1], 0 })
  else
    api.nvim_win_set_cursor(0, { line_of(view, section, path), 0 })
  end
  view:dispatch("ignore", { buf = view.files.buf, win = view.layout.files_win, range = range })
  H.flush(50)
end

local function messages(fn)
  local got, notify = {}, vim.notify
  vim.notify = function(msg)
    got[#got + 1] = msg
  end
  local ok, err = pcall(fn)
  vim.notify = notify
  assert(ok, err)
  return table.concat(got, "\n")
end

local function ignored(dir, path)
  return vim.system({ "git", "check-ignore", "-q", "--no-index", "--", path }, { cwd = dir }):wait().code == 0
end

local function tracked(dir, path)
  return vim.trim(H.git(dir, { "ls-files", "--", ":(literal)" .. path })) ~= ""
end

H.describe("i on untracked files", function()
  H.it("by path: an anchored line in .gitignore, the file gone from Untracked", function()
    local dir = repo({ ["a.txt"] = { "a" } })
    H.write(dir, "sub/build.log", { "x" })
    H.write(dir, "build.log", { "y" })
    local view = open()
    answer(".gitignore: /sub/build.log")
    local msg = messages(function()
      press(view, "untracked", "sub/build.log")
    end)
    H.eq(menu, {
      ".gitignore: /sub/build.log",
      ".gitignore: *.log",
      ".git/info/exclude: /sub/build.log",
      ".git/info/exclude: *.log",
    })
    H.eq(H.read(dir, ".gitignore"), "/sub/build.log\n")
    H.ok(ignored(dir, "sub/build.log"))
    H.ok(not ignored(dir, "build.log"), "anchored: only that file")
    H.eq(H.find_entry(view, "untracked", "sub/build.log"), nil)
    H.ok(H.find_entry(view, "untracked", ".gitignore"), ".gitignore shows up to commit")
    H.ok(msg:find(".gitignore: added /sub/build.log", 1, true), msg)
    H.eq(#asked, 0, "nothing tracked: no question")
  end)

  H.it("by extension: *.ext at any depth", function()
    local dir = repo({ ["a.txt"] = { "a" } })
    H.write(dir, "x.log", { "x" })
    H.write(dir, "deep/er/y.log", { "y" })
    local view = open()
    answer(".gitignore: *.log")
    press(view, "untracked", "x.log")
    H.eq(H.read(dir, ".gitignore"), "*.log\n")
    H.eq(H.find_entry(view, "untracked", "x.log"), nil)
    H.eq(H.find_entry(view, "untracked", "deep/er/y.log"), nil)
  end)

  H.it("in .git/info/exclude: no .gitignore", function()
    local dir = repo({ ["a.txt"] = { "a" } })
    H.write(dir, "notes.md", { "x" })
    local view = open()
    answer(".git/info/exclude: /notes.md")
    press(view, "untracked", "notes.md")
    H.ok(H.read(dir, ".git/info/exclude"):find("\n/notes.md\n$"), H.read(dir, ".git/info/exclude"))
    H.eq(H.read(dir, ".gitignore"), nil)
    H.eq(H.find_entry(view, "untracked", "notes.md"), nil)
    H.eq(#H.entries(view), 0, "nothing left to show")
  end)

  H.it("a directory of the tree: dir/, no extension choices", function()
    local dir = repo({ ["a.txt"] = { "a" } })
    H.write(dir, "out.d/a.o", { "x" })
    H.write(dir, "out.d/sub/b.o", { "y" })
    H.write(dir, "keep.o", { "z" })
    local view = open()
    answer(".gitignore: /out.d/")
    press(view, "untracked", "out.d")
    H.eq(menu, { ".gitignore: /out.d/", ".git/info/exclude: /out.d/" }, "a dot in a directory is no extension")
    H.eq(H.read(dir, ".gitignore"), "/out.d/\n")
    H.eq(H.find_entry(view, "untracked", "out.d/a.o"), nil)
    H.eq(H.find_entry(view, "untracked", "out.d/sub/b.o"), nil)
    H.ok(H.find_entry(view, "untracked", "keep.o"))
  end)

  H.it("visual: every selected file; a directory takes the files in it", function()
    local dir = repo({ ["a.txt"] = { "a" } })
    H.write(dir, "d/x.tmp", { "x" })
    H.write(dir, "e.tmp", { "e" })
    H.write(dir, "f.bak", { "f" })
    local view = open()
    answer(".gitignore: /d/, /e.tmp, /f.bak")
    press(view, "untracked", { "d", "f.bak" })
    H.eq(menu, { ".gitignore: /d/, /e.tmp, /f.bak", ".git/info/exclude: /d/, /e.tmp, /f.bak" })
    H.eq(H.read(dir, ".gitignore"), "/d/\n/e.tmp\n/f.bak\n")
    -- files only: one pattern per extension
    H.write(dir, "g.tmp", { "g" })
    H.write(dir, "h.tmp", { "h" })
    view:refresh()
    answer(".gitignore: *.tmp")
    press(view, "untracked", { "g.tmp", "h.tmp" })
    H.ok(vim.tbl_contains(menu, ".gitignore: *.tmp"), vim.inspect(menu))
    H.eq(H.read(dir, ".gitignore"), "/d/\n/e.tmp\n/f.bak\n*.tmp\n")
  end)

  H.it("names with wildcards, a leading # or !, trailing spaces are escaped", function()
    local dir = repo({ ["a.txt"] = { "a" } })
    local names = { "a[1]*?.txt", "#hash", "!bang", "back\\slash", "space " }
    for _, n in ipairs(names) do
      H.write(dir, n, { "x" })
    end
    H.write(dir, "a1xy.txt", { "not me" })
    local view = open()
    for _, n in ipairs(names) do
      answer(".git/info/exclude: " .. require("diffmerge.ignore").path_pattern(n))
      press(view, "untracked", n)
      H.ok(ignored(dir, n), n)
    end
    H.ok(not ignored(dir, "a1xy.txt"), "the wildcards matched only themselves")
    H.ok(H.read(dir, ".git/info/exclude"):find("/a\\[1]\\*\\?.txt\n", 1, true))
    H.ok(H.read(dir, ".git/info/exclude"):find("/space\\ \n", 1, true))
  end)

  H.it("appends after a last line without newline, keeps CRLF, never twice", function()
    local dir = repo({ [".gitignore"] = "*.o\r\n/tmp" })
    H.write(dir, "x.log", { "x" })
    H.write(dir, "y.log", { "y" })
    local view = open()
    answer(".gitignore: /x.log")
    press(view, "untracked", "x.log")
    H.eq(H.read(dir, ".gitignore"), "*.o\r\n/tmp\r\n/x.log\r\n")
    -- already there (e.g. a later rule takes it back)
    H.write(dir, ".gitignore", "*.o\r\n/tmp\r\n/x.log\r\n!x.log\r\n")
    view:refresh()
    answer(".gitignore: /x.log")
    local msg = messages(function()
      press(view, "untracked", "x.log")
    end)
    H.eq(H.read(dir, ".gitignore"), "*.o\r\n/tmp\r\n/x.log\r\n!x.log\r\n")
    H.ok(msg:find("has /x.log already", 1, true), msg)
    H.ok(msg:find("still not ignored", 1, true), msg)
  end)

  H.it("refused: .gitignore itself, an unsaved .gitignore", function()
    local dir = repo({ ["a.txt"] = { "a" }, [".gitignore"] = { "*.o" } })
    H.write(dir, ".gitignore", { "*.o", "*.p" })
    H.write(dir, "new.txt", { "n" })
    local view = open()
    answer("never")
    local msg = messages(function()
      press(view, "unstaged", ".gitignore")
    end)
    H.ok(msg:find(".gitignore itself", 1, true), msg)
    H.eq(menu, nil, "no menu")
    -- an unsaved buffer of the file to write
    vim.cmd("tabnew " .. vim.fn.fnameescape(dir .. "/.gitignore"))
    vim.cmd("normal! Gox")
    local buf = api.nvim_get_current_buf()
    vim.cmd("tabprevious")
    api.nvim_set_current_win(view.layout.files_win)
    answer(".gitignore: /new.txt")
    msg = messages(function()
      press(view, "untracked", "new.txt")
    end)
    H.ok(msg:find("unsaved changes in .gitignore", 1, true), msg)
    H.ok(H.find_entry(view, "untracked", "new.txt"))
    -- saved: written, and the buffer shows it
    api.nvim_buf_call(buf, function()
      vim.cmd("silent write")
    end)
    answer(".gitignore: /new.txt")
    press(view, "untracked", "new.txt")
    H.eq(H.buf_lines(buf), { "*.o", "*.p", "x", "/new.txt" })
    H.eq(vim.bo[buf].modified, false)
  end)

  H.it("a stash and its files are not ignored", function()
    local dir = repo({ ["a.txt"] = { "a" } })
    H.write(dir, "a.txt", { "b" })
    H.write(dir, "d/e.txt", { "e" })
    H.git(dir, { "stash", "-q", "-u" })
    local view = open()
    local sec
    for _, s in ipairs(view.status.sections) do
      sec = s.stash and s or sec
    end
    view.files.collapsed[sec.id] = false
    view.files:render()
    for _, at in ipairs({ "a.txt", "d" }) do
      answer("never")
      menu = nil
      local msg = messages(function()
        press(view, sec.id, at)
      end)
      H.ok(msg:find("a stash is not ignored", 1, true), at .. ": " .. msg)
      H.eq(menu, nil, at)
    end
    H.eq(H.read(dir, ".gitignore"), nil)
  end)

  H.it("conflicts are not ignored", function()
    local dir = repo({ ["c.txt"] = { "base" }, ["d/f.txt"] = { "base" } })
    H.git(dir, { "checkout", "-q", "-b", "other" })
    H.commit(dir, "other", { ["c.txt"] = { "theirs" }, ["d/f.txt"] = { "theirs" } })
    H.git(dir, { "checkout", "-q", "main" })
    H.commit(dir, "mine", { ["c.txt"] = { "mine" }, ["d/f.txt"] = { "mine" } })
    vim.system({ "git", "merge", "-q", "other" }, { cwd = dir }):wait()
    local view = open()
    for _, at in ipairs({ "c.txt", "d" }) do
      answer("never")
      menu = nil
      local msg = messages(function()
        press(view, "conflicts", at)
      end)
      H.ok(msg:find("resolve the conflict first", 1, true), at .. ": " .. msg)
      H.eq(menu, nil, at)
    end
    H.eq(H.read(dir, ".gitignore"), nil)
  end)
end)

H.describe("i on tracked files", function()
  H.it("committed: asks; no keeps everything, yes stops tracking (file kept)", function()
    local dir = repo({ ["cfg.lua"] = { "a" }, ["b.txt"] = { "b" } })
    H.write(dir, "cfg.lua", { "local" })
    local view = open()
    confirm_answer = 2
    answer(".gitignore: /cfg.lua")
    press(view, "unstaged", "cfg.lua")
    H.eq(#asked, 1)
    H.ok(asked[1]:find("cfg.lua is tracked.", 1, true), asked[1])
    H.ok(asked[1]:find("git rm --cached", 1, true), asked[1])
    H.ok(asked[1]:find("your working tree is left as it is", 1, true), asked[1])
    H.ok(asked[1]:find("your next commit deletes it from the repository", 1, true), asked[1])
    H.ok(not asked[1]:find("yours only", 1, true), asked[1])
    H.eq(H.read(dir, ".gitignore"), nil)
    H.ok(tracked(dir, "cfg.lua"))
    confirm_answer = 1
    answer(".gitignore: /cfg.lua")
    press(view, "unstaged", "cfg.lua")
    H.eq(H.read(dir, ".gitignore"), "/cfg.lua\n")
    H.ok(not tracked(dir, "cfg.lua"))
    H.eq(H.read(dir, "cfg.lua"), "local\n", "the file stays")
    H.ok(H.find_entry(view, "staged", "cfg.lua"), "its deletion is staged")
    H.eq(H.find_entry(view, "staged", "cfg.lua").status, "D")
    H.eq(H.find_entry(view, "untracked", "cfg.lua"), nil)
  end)

  H.it("exclude: says the deletion still goes to everyone", function()
    local dir = repo({ ["cfg.lua"] = { "a" } })
    H.write(dir, "cfg.lua", { "local" })
    local view = open()
    answer(".git/info/exclude: /cfg.lua")
    press(view, "unstaged", "cfg.lua")
    H.ok(asked[1]:find(".git/info/exclude is yours only, but the deletion goes to everyone", 1, true), asked[1])
    H.ok(not tracked(dir, "cfg.lua"))
  end)

  H.it("a directory: every tracked file in it, also those without changes", function()
    local dir = repo({ ["vendor/a.c"] = { "a" }, ["vendor/b.c"] = { "b" }, ["vendor/c/d.c"] = { "d" }, ["main.c"] = { "m" } })
    H.write(dir, "vendor/a.c", { "A" })
    H.write(dir, "vendor/new.c", { "n" })
    H.write(dir, "vendor/c/e.c", { "e" })
    local view = open()
    answer(".gitignore: /vendor/")
    press(view, "untracked", "vendor")
    H.ok(asked[1]:find("3 files are tracked: vendor/a.c, vendor/b.c, vendor/c/d.c.", 1, true), asked[1])
    H.ok(asked[1]:find("your next commit deletes them", 1, true), asked[1])
    H.eq(vim.trim(H.git(dir, { "ls-files" })), "main.c")
    H.eq(H.read(dir, ".gitignore"), "/vendor/\n")
    H.eq(H.find_entry(view, "untracked", "vendor/new.c"), nil)
    for _, p in ipairs({ "vendor/a.c", "vendor/b.c", "vendor/c/d.c" }) do
      H.eq(H.find_entry(view, "staged", p).status, "D", p)
    end
  end)

  H.it("staged but never committed: only unstaged, nothing asked", function()
    local dir = repo({ ["a.txt"] = { "a" } })
    H.write(dir, "secret.env", { "k=v" })
    H.git(dir, { "add", "secret.env" })
    local view = open()
    answer(".gitignore: /secret.env")
    local msg = messages(function()
      press(view, "staged", "secret.env")
    end)
    H.eq(#asked, 0)
    H.ok(not tracked(dir, "secret.env"))
    H.eq(H.find_entry(view, "staged", "secret.env"), nil)
    H.eq(H.find_entry(view, "untracked", "secret.env"), nil)
    H.ok(msg:find("1 file no longer tracked", 1, true), msg)
  end)

  H.it("mixed: names the committed ones and the only staged ones", function()
    local dir = repo({ ["a.log"] = { "a" } })
    H.write(dir, "a.log", { "A" })
    H.write(dir, "b.log", { "b" })
    H.git(dir, { "add", "b.log" })
    local view = open()
    answer(".gitignore: /a.log, /b.log")
    -- Staged b.log, Unstaged a.log: a section each, so the whole panel
    view.files.tree = false
    view.files:render()
    api.nvim_set_current_win(view.layout.files_win)
    api.nvim_win_set_cursor(0, { line_of(view, "staged", "b.log"), 0 })
    view:dispatch("ignore", {
      buf = view.files.buf,
      win = view.layout.files_win,
      range = { line_of(view, "staged", "b.log"), line_of(view, "unstaged", "a.log") },
    })
    H.flush(50)
    H.ok(asked[1]:find("2 files are tracked: a.log, b.log.", 1, true), asked[1])
    H.ok(asked[1]:find("your next commit deletes a.log from the repository", 1, true), asked[1])
    H.ok(asked[1]:find("b.log was never committed: it is only unstaged", 1, true), asked[1])
    H.ok(not tracked(dir, "a.log") and not tracked(dir, "b.log"))
  end)

  H.it("a staged rename counts as committed", function()
    local dir = repo({ ["old.txt"] = { "x" } })
    H.git(dir, { "mv", "old.txt", "new.txt" })
    local view = open()
    answer(".gitignore: /new.txt")
    press(view, "staged", "new.txt")
    H.eq(#asked, 1)
    H.ok(asked[1]:find("deletes it from the repository", 1, true), asked[1])
  end)

  H.it("by extension: other tracked files of it stay tracked (and are counted)", function()
    local dir = repo({ ["a.log"] = { "a" }, ["sub/b.log"] = { "b" }, ["c.log"] = { "c" } })
    H.write(dir, "a.log", { "A" })
    local view = open()
    answer(".gitignore: *.log")
    press(view, "unstaged", "a.log")
    H.ok(asked[1]:find("- 2 other tracked files matching *.log stay tracked", 1, true), asked[1])
    H.ok(not tracked(dir, "a.log"))
    H.ok(tracked(dir, "sub/b.log") and tracked(dir, "c.log"))
  end)

  H.it("staged content neither committed nor on disk: refused (it would be lost)", function()
    local dir = repo({ ["a.txt"] = { "a" } })
    H.write(dir, "a.txt", { "staged" })
    H.git(dir, { "add", "a.txt" })
    H.write(dir, "a.txt", { "worktree" })
    H.write(dir, "new.txt", { "staged" })
    H.git(dir, { "add", "new.txt" })
    H.write(dir, "new.txt", { "worktree" })
    local view = open()
    for _, p in ipairs({ "a.txt", "new.txt" }) do
      answer(".gitignore: /" .. p)
      local msg = messages(function()
        press(view, "staged", p)
      end)
      H.ok(msg:find("the staged changes of " .. p .. " are neither committed nor on disk", 1, true), msg)
      H.ok(tracked(dir, p), p)
    end
    H.eq(#asked, 0)
    H.eq(H.read(dir, ".gitignore"), nil)
    -- all of it staged, or none: nothing is lost
    H.git(dir, { "add", "a.txt" })
    view:refresh()
    answer(".gitignore: /a.txt")
    press(view, "staged", "a.txt")
    H.ok(not tracked(dir, "a.txt"))
  end)

  H.it("no commit yet: staged content not on disk is kept too", function()
    local dir = repo()
    H.write(dir, "a.txt", { "staged" })
    H.git(dir, { "add", "a.txt" })
    H.write(dir, "a.txt", { "worktree" })
    H.write(dir, "b.txt", { "b" })
    H.git(dir, { "add", "b.txt" })
    local view = open()
    answer(".gitignore: /a.txt")
    local msg = messages(function()
      press(view, "staged", "a.txt")
    end)
    H.ok(msg:find("the staged changes of a.txt are neither committed nor on disk", 1, true), msg)
    H.ok(tracked(dir, "a.txt"))
    answer(".gitignore: /b.txt")
    press(view, "staged", "b.txt")
    H.eq(#asked, 0, "nothing committed")
    H.ok(not tracked(dir, "b.txt"))
    -- intent to add: nothing staged to lose
    H.write(dir, "ita.txt", { "i" })
    H.git(dir, { "add", "-N", "ita.txt" })
